def _savefig_multi(fig, basename, formats, dpi):
    """Save *fig* once per entry in *formats*, returning the paths written.

    A failure saving one format (e.g. missing Pillow for "jpg") is
    reported with a warning and does not prevent the other formats from
    being saved.
    """
    saved = []
    for fmt in formats:
        fmt_clean = str(fmt).lower().lstrip(".")
        path = f"{basename}.{fmt_clean}"
        try:
            if fmt_clean in ("jpg", "jpeg"):
                # JPEG has no alpha channel; force an opaque white background
                # so a transparent figure facecolor doesn't turn black.
                fig.savefig(path, dpi=dpi, format="jpg", facecolor="white")
            else:
                fig.savefig(path, dpi=dpi, format=fmt_clean)
            saved.append(path)
        except Exception as exc:
            warnings.warn(f"Could not save {path!r} ({exc}).")
    return saved


def _plot_ellipse_map(sites, xs, ys, bm, display_coords, color_by,
                      ellipse_scale, ellipse_fraction, ellipse_npts):
    if ellipse_scale == "auto":
        base_radius = ellipse_fraction * _median_nn_spacing(xs, ys)
        if base_radius <= 0:
            base_radius = 1.0
            warnings.warn(
                "Automatic ellipse scale came out non-positive "
                "(degenerate site layout?) -- falling back to 1.0."
            )
    else:
        base_radius = float(ellipse_scale)

    sev = np.array([_severity(s["C"], color_by) for s in sites])

    fig, ax = plt.subplots(figsize=FIGSIZE)
    _draw_basemap(ax, bm, display_coords)

    norm = Normalize(vmin=float(np.nanmin(sev)), vmax=float(np.nanmax(sev)))
    cmap = plt.get_cmap(CMAP_ELLIPSE)

    patches = []
    for s, x0, y0 in zip(sites, xs, ys):
        ex, ey = _ellipse_points(s["C"], n=ellipse_npts)
        verts = np.column_stack([x0 + base_radius * ex, y0 + base_radius * ey])
        patches.append(MplPolygon(verts, closed=True))

    face_colors = [cmap(norm(v)) for v in sev]
    pc = PatchCollection(patches, facecolor=face_colors,
                         edgecolor=ELLIPSE_EDGECOLOR, linewidths=ELLIPSE_LW,
                         alpha=ELLIPSE_ALPHA, zorder=5)
    ax.add_collection(pc)
    ax.plot(xs, ys, "+", color="black", ms=4, zorder=6)

    if SITE_LABELS:
        for s, x0, y0 in zip(sites, xs, ys):
            ax.annotate(s["name"], (x0, y0), fontsize=LABEL_FONTSIZE,
                       xytext=(3, 3), textcoords="offset points", zorder=7)

    sm = ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=ax, shrink=0.8)
    cbar.set_label(_severity_label(color_by), fontsize=LABEL_FONTSIZE_AXES)
    cbar.ax.tick_params(labelsize=TICK_FONTSIZE)

    xlabel, ylabel = _axis_labels(display_coords)
    ax.set_xlabel(xlabel, fontsize=LABEL_FONTSIZE_AXES)
    ax.set_ylabel(ylabel, fontsize=LABEL_FONTSIZE_AXES)
    ax.tick_params(labelsize=TICK_FONTSIZE)
    ax.set_aspect("equal")
    ax.set_title(TITLE, fontsize=LABEL_FONTSIZE_AXES + 1)
    ax.autoscale_view()
    fig.tight_layout()
    return fig


def _plot_gb_panel(sites, xs, ys, bm, display_coords):
    """2x2 panel of Groom-Bailey twist / shear / gain / anisotropy maps."""
    gb = [_gb_decompose(s["C"]) for s in sites]
    n_undefined = sum(1 for g in gb if g is None)
    if n_undefined:
        warnings.warn(
            f"{n_undefined} of {len(sites)} site(s) have det(C) <= 0 (or a "
            "non-converged fit) and are excluded from the Groom-Bailey "
            "panel colour scales; shown as grey 'x' markers. See "
            "_gb_decompose docstring."
        )

    panels = (
        ("twist_deg", "Twist [deg]"),
        ("shear_deg", "Shear [deg]"),
        ("gain", "Gain"),
        ("anisotropy", "Anisotropy (split s)"),
    )

    fig, axs = plt.subplots(2, 2, figsize=GB_FIGSIZE, sharex=True, sharey=True)
    xlabel, ylabel = _axis_labels(display_coords)

    for ax, (key, label) in zip(axs.ravel(), panels):
        _draw_basemap(ax, bm, display_coords)

        defined = [(x, y, g[key]) for x, y, g in zip(xs, ys, gb) if g is not None]
        undefined = [(x, y) for x, y, g in zip(xs, ys, gb) if g is None]

        if defined:
            dx, dy, dv = map(np.array, zip(*defined))
            sca = ax.scatter(dx, dy, c=dv, cmap=GB_CMAP, s=GB_MARKER_SIZE,
                             edgecolor="black", linewidths=0.5, zorder=5)
            cbar = fig.colorbar(sca, ax=ax, shrink=0.85)
            cbar.ax.tick_params(labelsize=TICK_FONTSIZE)
        if undefined:
            ux, uy = map(np.array, zip(*undefined))
            ax.scatter(ux, uy, marker="x", color=GB_UNDEFINED_COLOR,
                      s=GB_MARKER_SIZE, zorder=5,
                      label="det(C) <= 0 / not converged")
            ax.legend(fontsize=LABEL_FONTSIZE, loc="best")

        ax.set_title(label, fontsize=LABEL_FONTSIZE_AXES)
        ax.tick_params(labelsize=TICK_FONTSIZE)
        ax.set_aspect("equal")

    for ax in axs[-1, :]:
        ax.set_xlabel(xlabel, fontsize=LABEL_FONTSIZE_AXES)
    for ax in axs[:, 0]:
        ax.set_ylabel(ylabel, fontsize=LABEL_FONTSIZE_AXES)

    fig.suptitle("Groom-Bailey decomposition of C "
                 "(Groom & Bailey, 1989, doi:10.1029/JB094iB02p01913)",
                 fontsize=LABEL_FONTSIZE_AXES + 1)
    fig.tight_layout()
    return fig


def plot_distortion_ellipses(
    distortion_file=DISTORTION_FILE,
    site_dat=SITE_DAT,
    display_coords=DISPLAY_COORDS,
    distortion_kind=DISTORTION_KIND,
    ellipse_scale=ELLIPSE_SCALE,
    ellipse_fraction=ELLIPSE_FRACTION,
    ellipse_npts=ELLIPSE_NPTS,
    color_by=COLOR_BY,
    gb_decomp_enable=GB_DECOMP_ENABLE,
    output_basename=OUTPUT_BASENAME,
    output_formats=OUTPUT_FORMATS,
):
    """Read a FEMTIC distortion file + site.dat and plot distortion ellipses.

    Also produces the optional Groom-Bailey 2x2 decomposition panel when
    ``gb_decomp_enable`` (or the module-level ``GB_DECOMP_ENABLE`` CONFIG
    flag) is True.

    All tunable parameters double as module-level CONFIG variables (see
    the CONFIG block above); this function signature exists so the plot
    can also be called programmatically, e.g. from an ensemble-QC loop.

    Returns
    -------
    (ellipse_fig, gb_fig) : gb_fig is None when gb_decomp_enable is False.
    """
    if display_coords not in ("model", "utm", "latlon"):
        raise ValueError(
            f"DISPLAY_COORDS={display_coords!r} not recognised. "
            "Choose 'model', 'utm', or 'latlon'."
        )
    if distortion_kind not in ("full", "prime"):
        raise ValueError(
            f"DISTORTION_KIND={distortion_kind!r} not recognised. "
            "Choose 'full' or 'prime'."
        )
    if color_by not in ("condition", "determinant", "gain"):
        raise ValueError(
            f"COLOR_BY={color_by!r} not recognised. "
            "Choose 'condition', 'determinant', or 'gain'."
        )

    sites = _load_sites_with_distortion(distortion_file, site_dat, distortion_kind)

    xs, ys = [], []
    for s in sites:
        x, y = _plot_coords(s, display_coords)
        xs.append(x)
        ys.append(y)
    xs = np.asarray(xs)
    ys = np.asarray(ys)

    bm = _fetch_basemap_if_enabled(sites, display_coords)

    ellipse_fig = _plot_ellipse_map(
        sites, xs, ys, bm, display_coords, color_by,
        ellipse_scale, ellipse_fraction, ellipse_npts,
    )
    saved = _savefig_multi(ellipse_fig, output_basename, output_formats, DPI)
    if SHOW:
        plt.show()
    print(f"[femtic_plot_distort] {len(sites)} site(s) plotted -> "
          f"{', '.join(saved) if saved else '(no files saved)'}")

    gb_fig = None
    if gb_decomp_enable:
        gb_fig = _plot_gb_panel(sites, xs, ys, bm, display_coords)
        gb_basename = f"{output_basename}{GB_BASENAME_SUFFIX}"
        gb_saved = _savefig_multi(gb_fig, gb_basename, output_formats, DPI)
        if SHOW:
            plt.show()
        print(f"[femtic_plot_distort] Groom-Bailey panel -> "
              f"{', '.join(gb_saved) if gb_saved else '(no files saved)'}")

    plt.close(ellipse_fig)
    if gb_fig is not None:
        plt.close(gb_fig)

    return ellipse_fig, gb_fig


if __name__ == "__main__":
    plot_distortion_ellipses()
