def _fetch_basemap_if_enabled(sites, display_coords):
    if not BASEMAP_ENABLE:
        return None
    margin = SRTM_MARGIN_DEG
    lons = [s["lon"] for s in sites]
    lats = [s["lat"] for s in sites]
    bounds = (min(lons) - margin, min(lats) - margin,
              max(lons) + margin, max(lats) + margin)
    target_epsg = None if display_coords == "latlon" else _utm_epsg(
        UTM_ZONE, UTM_NORTHERN
    )
    bm = _get_srtm_hillshade(bounds, target_epsg, SRTM_CACHE_DIR,
                              SRTM_PRODUCT, SRTM_LOCAL_FILE)
    if bm is None:
        print("[femtic_plot_distort] Basemap unavailable -- "
              "plotting on a plain background.")
    return bm


