def _get_srtm_hillshade(bounds, target_epsg, cache_dir, product, local_file):
    """Fetch/clip an SRTM tile and return a hillshade ready for imshow().

    Parameters
    ----------
    bounds : (west, south, east, north) in decimal degrees.
    target_epsg : int or None
        None -> keep geographic (EPSG:4326), matching DISPLAY_COORDS="latlon".
        int  -> reproject to this UTM EPSG code, matching "utm"/"model".
    cache_dir : str
        Directory for the downloaded/clipped GeoTIFF.
    product : str
        "SRTM1" or "SRTM3", forwarded to the `elevation` package.
    local_file : str or None
        Pre-downloaded GeoTIFF; if given, no download is attempted.

    Returns
    -------
    dict with keys "extent" ((xmin, xmax, ymin, ymax) in target units,
    metres for a UTM EPSG, degrees for geographic), "hillshade" (2-D
    array), "elevation" (2-D array) -- or None if the basemap could not
    be produced (missing packages, no network, download failure, ...).
    All failure modes are handled by returning None with a warning
    rather than raising, so a missing basemap never aborts the ellipse
    plot itself.
    """
    try:
        import rasterio
        from rasterio.warp import calculate_default_transform, reproject, Resampling
    except ImportError:
        warnings.warn(
            "rasterio is not installed -- skipping SRTM basemap. "
            "Install it, or set BASEMAP_ENABLE = False."
        )
        return None

    tif_path = local_file
    if tif_path is None:
        try:
            import elevation
        except ImportError:
            warnings.warn(
                "The `elevation` package is not installed and no "
                "SRTM_LOCAL_FILE was given -- skipping SRTM basemap. "
                "Install `elevation` (requires GDAL) for auto-download, "
                "or point SRTM_LOCAL_FILE at a pre-downloaded GeoTIFF."
            )
            return None
        os.makedirs(cache_dir, exist_ok=True)
        tif_path = os.path.join(cache_dir, "srtm_clip.tif")
        try:
            elevation.clip(bounds=bounds, output=os.path.abspath(tif_path),
                            product=product)
        except Exception as exc:
            warnings.warn(
                f"SRTM download/clip failed ({exc}) -- skipping basemap. "
                "This usually means no internet access or GDAL/`eio` is "
                "not set up on this machine; set SRTM_LOCAL_FILE to use a "
                "pre-downloaded GeoTIFF instead."
            )
            return None

    try:
        with rasterio.open(tif_path) as src:
            elev = src.read(1).astype(float)
            elev[elev <= -32768] = np.nan  # SRTM void / no-data sentinel
            src_transform = src.transform
            src_crs = src.crs
            src_bounds = src.bounds
            src_width, src_height = src.width, src.height

        if target_epsg is None:
            dst_transform = src_transform
            dst_elev = elev
            height, width = elev.shape
        else:
            dst_crs = rasterio.crs.CRS.from_epsg(target_epsg)
            dst_transform, width, height = calculate_default_transform(
                src_crs, dst_crs, src_width, src_height, *src_bounds
            )
            dst_elev = np.full((height, width), np.nan, dtype=float)
            reproject(
                source=elev,
                destination=dst_elev,
                src_transform=src_transform,
                src_crs=src_crs,
                dst_transform=dst_transform,
                dst_crs=dst_crs,
                resampling=Resampling.bilinear,
            )

        dx = abs(dst_transform.a)
        dy = abs(dst_transform.e)
        if target_epsg is None:
            # Geographic pixel size -> approximate metres at mean latitude,
            # needed only so LightSource.hillshade's slope calculation is
            # not wildly distorted; the displayed axes stay in degrees.
            mean_lat = 0.5 * (bounds[1] + bounds[3])
            dx = dx * 111320.0 * np.cos(np.radians(mean_lat))
            dy = dy * 110540.0

        fill_value = np.nanmin(dst_elev) if np.isfinite(np.nanmin(dst_elev)) else 0.0
        ls = LightSource(azdeg=HILLSHADE_AZIMUTH, altdeg=HILLSHADE_ALTITUDE)
        hillshade = ls.hillshade(
            np.nan_to_num(dst_elev, nan=fill_value),
            vert_exag=HILLSHADE_VERT_EXAG, dx=dx, dy=dy,
        )

        xmin = dst_transform.c
        ymax = dst_transform.f
        xmax = xmin + width * dst_transform.a
        ymin = ymax + height * dst_transform.e
        extent = (xmin, xmax, min(ymin, ymax), max(ymin, ymax))
        return dict(extent=extent, hillshade=hillshade, elevation=dst_elev)

    except Exception as exc:
        warnings.warn(f"Failed to process SRTM raster ({exc}) -- skipping basemap.")
        return None


