def _read_distortion_site_ids(path):
    """Return the site-ID column of a FEMTIC distortion file, in file order.

    ``fem.read_distortion_file`` parses this same column internally but
    does not return it, so it is re-read here to keep the two arrays
    (matrices, IDs) aligned without assuming any particular ordering in
    ``site.dat``.
    """
    lines = Path(path).read_text().strip().splitlines()
    ids = []
    for line in lines[1:]:
        parts = line.split()
        if not parts:
            continue
        ids.append(int(parts[0]))
    return ids


def _load_sites_with_distortion(distortion_file, site_dat, distortion_kind):
    """Merge FEMTIC distortion matrices with site.dat coordinates.

    Returns a list of dicts, one per matched site, with keys
    ``sitenum, name, lat, lon, elev, easting, northing, C``.
    """
    c, c_dash = fem.read_distortion_file(distortion_file)
    site_ids = _read_distortion_site_ids(distortion_file)
    if len(site_ids) != len(c):
        raise RuntimeError(
            f"{distortion_file}: parsed {len(site_ids)} site IDs but "
            f"{len(c)} matrices -- check the file format."
        )

    site_records = fem.read_site_dat(site_dat)
    by_sitenum = {r["sitenum"]: r for r in site_records}

    sites = []
    missing = []
    for sid, C, Cp in zip(site_ids, c, c_dash):
        rec = by_sitenum.get(sid)
        if rec is None:
            missing.append(sid)
            continue
        sites.append(dict(
            sitenum=sid,
            name=rec["name"],
            lat=rec["lat"],
            lon=rec["lon"],
            elev=rec["elev"],
            easting=rec["easting"],
            northing=rec["northing"],
            C=(C if distortion_kind == "full" else Cp),
        ))
    if missing:
        warnings.warn(
            f"{len(missing)} distortion-file site number(s) not found in "
            f"{site_dat}: {missing}"
        )
    if not sites:
        raise RuntimeError(
            "No distortion-file site numbers matched any entry in "
            f"{site_dat} -- check that DISTORTION_FILE and SITE_DAT "
            "correspond to the same run."
        )
    return sites


def _ellipse_points(C, n=91):
    """Image of the unit circle under 2x2 matrix C, as (x, y) arrays."""
    theta = np.linspace(0.0, 2.0 * np.pi, n)
    circle = np.vstack([np.cos(theta), np.sin(theta)])
    out = C @ circle
    return out[0], out[1]


def _severity(C, metric):
    """Scalar distortion-severity metric for a 2x2 matrix C."""
    s = np.linalg.svd(C, compute_uv=False)
    if metric == "condition":
        return float(s[0] / s[1]) if s[1] > 0 else np.inf
    if metric == "determinant":
        return float(abs(np.linalg.det(C)))
    if metric == "gain":
        return float(np.mean(s))
    raise ValueError(
        f"_severity: unknown metric={metric!r}. "
        "Choose 'condition', 'determinant', or 'gain'."
    )


def _median_nn_spacing(xs, ys):
    """Median nearest-neighbour distance among a set of 2-D points."""
    n = len(xs)
    if n < 2:
        return 1.0
    xs = np.asarray(xs)
    ys = np.asarray(ys)
    d = np.hypot(xs[:, None] - xs[None, :], ys[:, None] - ys[None, :])
    np.fill_diagonal(d, np.inf)
    return float(np.median(d.min(axis=1)))


def _gb_model(params):
    """C(twist, shear, s, g) = g * T(twist) @ S(shear) @ diag(1+s, 1-s).

    T(twist) is a pure rotation; S(shear) = [[cos, sin], [sin, cos]] is a
    symmetric shear along the +/-45 deg diagonal axes; A = diag(1+s, 1-s)
    is the anisotropy ("channelling") term. This is algebraically
    equivalent to the classic Groom & Bailey (1989) tan-based
    T/S/A matrices (t = tan(twist), e = tan(shear)), just written directly
    in terms of bounded angles, which is nicer to fit numerically.
    """
    tau, chi, s, g = params
    T = np.array([[np.cos(tau), -np.sin(tau)], [np.sin(tau), np.cos(tau)]])
    S = np.array([[np.cos(chi), np.sin(chi)], [np.sin(chi), np.cos(chi)]])
    A = np.diag([1.0 + s, 1.0 - s])
    return g * T @ S @ A


def _gb_decompose(C, *, rel_tol=1e-4):
    """Groom & Bailey (1989) twist/shear/gain/anisotropy decomposition of C.

    Solves ``C = g * T(twist) @ S(shear) @ diag(1+s, 1-s)`` for
    ``twist, shear in (-45 deg, 45 deg]``, ``s in (-1, 1)``, ``g > 0`` via
    a bounded, multi-start least-squares fit (see `_gb_model`). This is a
    4-parameter fit to the 4 independent entries of C, so an exact fit
    (residual ~ 0) is expected whenever one exists.

    Limitation -- negative-determinant sites: ``det(C_model)`` is always
    ``>= 0`` for this parameterisation (``det(T)=1``, ``det(S)=cos(2*shear)
    >= 0`` within the fitted range, ``det(A)=1-s**2 >= 0``), so a real
    distortion matrix with ``det(C) < 0`` cannot be exactly reproduced.
    This is a known property of the classic Groom-Bailey model, not a bug
    here -- see Lilley (2016, doi:10.1071/EG14093), "Negative
    determinants: the situation with distortion matrices, and
    Groom-Bailey analysis". Such sites are flagged by returning ``None``;
    use the ellipse/condition-number plot (SVD-based, always defined) for
    them instead.

    Returns
    -------
    dict with keys ``twist_deg, shear_deg, gain, anisotropy`` (``s``), or
    ``None`` if ``det(C) <= 0`` or the fit did not converge to a good
    reconstruction (residual above ``rel_tol`` relative to ``norm(C)``).
    """
    if np.linalg.det(C) <= 0:
        return None

    def resid(params):
        return (_gb_model(params) - C).ravel()

    g0 = float(np.sqrt(abs(np.linalg.det(C)))) or 1.0
    starts = (
        [0.0, 0.0, 0.0, g0],
        [0.3, -0.3, 0.2, g0],
        [-0.3, 0.3, -0.2, g0],
    )
    bounds = (
        [-np.pi / 4, -np.pi / 4, -0.999, 1e-9],
        [np.pi / 4, np.pi / 4, 0.999, np.inf],
    )
    best = None
    for x0 in starts:
        res = least_squares(resid, x0, bounds=bounds)
        if best is None or res.cost < best.cost:
            best = res

    c_norm = float(np.linalg.norm(C))
    resid_norm = float(np.linalg.norm(resid(best.x)))
    if c_norm > 0 and resid_norm / c_norm > rel_tol:
        warnings.warn(
            f"_gb_decompose: fit residual {resid_norm:.3g} exceeds "
            f"{rel_tol:g} * ||C|| ({c_norm:.3g}) -- decomposition may be "
            "unreliable for this site."
        )
        return None

    tau, chi, s, g = best.x
    return dict(
        twist_deg=float(np.degrees(tau)),
        shear_deg=float(np.degrees(chi)),
        gain=float(g),
        anisotropy=float(s),
    )


